export function sanitizeNativeFailure(value = {}) {
  return {
    schemaVersion: 1,
    phase: phases.has(value?.phase) ? value.phase : 'unknown',
    invocation: invocations.has(value?.invocation) ? value.invocation : null,
    category: categories.has(value?.category) ? value.category : 'unknown',
    code: code(value?.code),
    firstCausalCode: code(value?.firstCausalCode),
  };
}
export function isNativeFailure(value) {
  if (!value || typeof value !== 'object' || Array.isArray(value)) return false;
  const expected = sanitizeNativeFailure(value);
  return Object.keys(value).length === Object.keys(expected).length &&
    Object.entries(expected).every(([key, item]) => Object.hasOwn(value, key) && value[key] === item);
}
function errorCode(error) {
  // Assertion messages can append private values. Only the exact frozen leading token survives.
  const token = typeof error?.message === 'string' ? /^([A-Z][A-Z0-9_]{0,199})(?=$|[\s:])/.exec(error.message)?.[1] : undefined;
  return code(token) !== unknown ? code(token) : code(error?.code);
}
export function nativeFailure(error, context = {}) {
  if (isNativeFailure(error?.nativeFailure)) {
    const retained = error.nativeFailure;
    return sanitizeNativeFailure({ ...context, ...retained,
      phase: retained.phase === 'unknown' ? context.phase : retained.phase,
      invocation: retained.invocation ?? context.invocation,
      category: retained.category === 'unknown' ? context.category : retained.category,
    });
  }
  let first = error;
  let causalContext;
  const seen = new Set();
  for (let depth = 0; depth < 8; depth++) {
    if (!first || typeof first !== 'object' || seen.has(first)) { first = null; break; }
    seen.add(first);
    if (isNativeFailure(first.nativeFailure)) causalContext = first.nativeFailure;
    const nested = first.cause ?? (Array.isArray(first.errors) ? first.errors[0] : undefined);
    if (nested === undefined) break;
    first = nested;
  }
  return sanitizeNativeFailure({ ...context,
    ...(causalContext ? {
      phase: causalContext.phase === 'unknown' ? context.phase : causalContext.phase,
      invocation: causalContext.invocation ?? context.invocation,
      category: causalContext.category === 'unknown' ? context.category : causalContext.category,
    } : {}), code: errorCode(error),
    firstCausalCode: causalContext?.firstCausalCode ?? errorCode(first),
  });
}
export function annotateNativeFailure(error, context = {}, retained) {
  const failure = retained ? sanitizeNativeFailure(retained) : nativeFailure(error, context);
  const result = error instanceof Error && Object.isExtensible(error) ? error : new Error(failure.code, { cause: error });
  result.nativeFailure = failure;
  return result;
}
export function reportNativeFailure(error, context = {}) {
  const failure = nativeFailure(error, context);
  if (process.connected && typeof process.send === 'function')
    process.send({ type: 'harness-native-failure', failure }, () => {});
  console.error('[harness-native-failure] ' + JSON.stringify(failure));
  return failure;
}
